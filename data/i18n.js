// Materials dictionary is loaded separately from kiranico_item_translations.json
// (816 monster-material lookups derived from 1429 scraped Kiranico ES/EN item pairs)
// and merged into I18N.materials at runtime by app.js.
I18N.materials = {};

function t(dict, key) {
  if (key === null || key === undefined) return key;
  return dict[key] || key;
}

function normalizeMaterialKey(s) {
  return s.replace(/\s+\+/g, "+").trim();
}

function translateMaterial(name) {
  return I18N.materials[normalizeMaterialKey(name)] || name;
}
