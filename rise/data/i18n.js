// Materials dictionary is loaded separately from kiranico_item_translations.json
// (816 monster-material lookups derived from 1429 scraped Kiranico ES/EN item pairs)
// and merged into I18N.materials at runtime by app.js.
I18N.materials = {};

function t(dict, key) {
  if (key === null || key === undefined) return key;
  return dict[key] || key;
}

// Decorations/weapons/armor sometimes name a material with the monster's
// full name (ex. "Volvidon Rickrack") while monsters.json has it under the
// same monster's shorthand nickname from the original Fextralife scrape
// (ex. "Volvi Rickrack") -- same real item, inconsistent source naming.
// Found by cross-checking every equipment material against monsters.json's
// material list for same-suffix / substring-prefix collisions (2026-08-08).
const MATERIAL_NAME_ALIASES = {
  "Volvidon Rickrack": "Volvi Rickrack",
  "Volvidon Carapace": "Volvi Carapace",
  "Magnamalo Soulprism": "Magna Soulprism",
  "Magnamalo Soulprism+": "Magna Soulprism+",
};

function normalizeMaterialKey(s) {
  const key = s.replace(/\s+\+/g, "+").trim();
  return MATERIAL_NAME_ALIASES[key] || key;
}

function translateMaterial(name) {
  const key = normalizeMaterialKey(name);
  if (I18N.materials[key]) return I18N.materials[key];
  // Materiales/Items catalog (app.js, loaded from data/items.json) --
  // translateMaterial() is defined here (loaded before app.js) but only
  // CALLED later during rendering, by which point itemsByName is populated,
  // so this forward reference resolves fine in classic-script scope.
  if (typeof itemsByName !== "undefined") {
    const it = itemsByName.get(name) || itemsByName.get(key);
    if (it && it.nameEs) return it.nameEs;
  }
  return name;
}
